# ---------------------------------------------------------------------------
section "the handover is recorded where it happened"
# A switch keeps the SAME session, and meta.json names the model the session started with - so
# without this line the transcript has two stretches of assistant turns by different models and
# nothing saying where one ends.
sw_reset
sw_window "$MLXREAL" ""
cad_mk_session "20260821T000000Z-switch"
