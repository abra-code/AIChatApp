#!/bin/sh
# Tests/93-model-switch.test.sh - changing the model of an open conversation, in place.
#
# WHAT A MODEL IS DECIDES WHAT HAS TO HAPPEN TO CHANGE IT, and that is the whole content of this
# file. A GGUF model is a llama-server this app owns, named in the agent's argv only as a port; an
# MLX model is a directory the agent maps itself, named in its argv; the on-device model is a
# backend flag. So one cell of the matrix - gguf to gguf - is a server restart under an agent that
# never notices, and every other cell has to REPLACE the agent process, which the app does by
# re-injecting states["config"] and letting the element stop the old one, spawn the new one and
# re-prime it from the transcript on screen.
#
# Those two mechanisms fail in opposite ways, silently, and the assertions here are mostly about
# which one ran: a cell that re-injects when it should have restarted leaves the conversation on a
# fresh agent with no history; a cell that restarts when it should have re-injected leaves the
# window titled with a model that is not answering it. Neither shows up as an error.
#
# The engine work is driven through sw(), which stubs the four things that touch the machine
# (launching llama-server, stopping one, claiming a port, probing Apple Intelligence). Everything
# else is real - the transport JSON is generated by the same builder the app ships, so the argv
# asserted below is the argv a window would actually get.
#
# POSIX sh only. Validate with "sh -n", never "bash -n".
. "${OMCTEST_LIB:?set OMCTEST_LIB, or run via: appletbuilder test}"
. "$OMCTEST_TESTS/lib.test.cadabra.sh"

cad_import_ids aichat.chat.engine.library.sh CE_
cad_import_ids aichat.library.sh BASE_
cad_import_ids aichat.history.library.sh HL_
CHAT_ID=1
# The ids this file writes through, asserted as literals so a rename reports itself once here
# instead of turning every assertion below it vacuously true.
check "the chat element is the id the switch injects into" "1"   "$CE_CHAT_ELEMENT_ID"
check "and the model bar is the button it renames"          "542" "$CE_CHAT_MODEL_BTN_ID"

lib() { cad_call_lib aichat.library.sh "$@"; }
# The loading overlay is inserted into declared slot 550 and removed again, so its own id only
# exists at runtime. Declared here rather than silently tripping the undeclared-id check.
ui_declare_ids "$BASE_CHAT_OVERLAY_ELEM_ID" "$HL_CAD_SUMMARIZE_PICKER_ID"

# ---------------------------------------------------------------------------
# Fixtures: models that EXIST, because model_engine tests the filesystem rather than the name.
MODELS="$OMCTEST_WORK/models"
/bin/mkdir -p "$MODELS"
GGUF="$MODELS/Tiny-Q4_K_M.gguf"
OTHER="$MODELS/Other-Q5_K_S.gguf"
/usr/bin/head -c 4096 /dev/zero > "$GGUF"
/usr/bin/head -c 4096 /dev/zero > "$OTHER"
MLXDIR="$MODELS/Mlx-Test-Model"
OTHERMLX="$MODELS/Mlx-Other-Model"
for d in "$MLXDIR" "$OTHERMLX"; do
    /bin/mkdir -p "$d"
    printf '{}' > "$d/config.json"
    /usr/bin/head -c 512 /dev/zero > "$d/model.safetensors"
done
# The PHYSICAL paths, which is what the mlx branch stamps and injects: under the harness $TMPDIR
# that is a real difference (/var -> /private/var), and asserting the input path would pass here
# and fail for the reason the resolution exists.
MLXREAL=$(cd "$MLXDIR" && pwd -P)
OTHERMLXREAL=$(cd "$OTHERMLX" && pwd -P)
FOUNDATION=$(cad_lib_var FOUNDATION_MODEL_ID aichat.model.library.sh)
check "the on-device sentinel is what the picker passes" "foundation:apple-on-device" "$FOUNDATION"

# A window uuid that is not this file's own: the picker's OK runs in the PICKER's window and acts
# on a chat window somewhere else, and a test using one uuid for both could not tell them apart.
SWIN="OMCTEST-switch-$$"

# ---------------------------------------------------------------------------
# sw <function> [args...] - the engine library with everything that touches the machine stubbed.
#
# NOT OPTIONAL, for the same reason 95's eng() is not: the real launch would spawn a llama-server
# against the developer's own bundle, and the real reaper walks `ps` for paths under the REAL
# $OMC_APP_BUNDLE_PATH, which on this machine is their running copy of the app.
#
# Each stub RECORDS rather than merely returning, because the cells differ in which of them runs
# and in what order - the two failures this file exists to catch are a launch that should not have
# happened and a stop that happened too early.
SW_LOG="$OMCTEST_WORK/switch-calls.log"
: > "$SW_LOG"

# Whether the element has already been given its new transport at the moment a stub is called.
# This is how "stopped AFTER the injection" is asserted: the order matters because the old agent
# may be mid-request against the outgoing server, and killing it first turns a switch into an
# error item in the transcript.
sw_seen_config() {
    if /usr/bin/grep -q 'omc_set_state config' "$OMCTEST_UI/journal.tsv" 2>/dev/null; then
        printf 'after-inject\n'
    else
        printf 'before-inject\n'
    fi
}

sw() {
    ( . "$OMC_APP_BUNDLE_PATH/Contents/Resources/Scripts/aichat.chat.engine.library.sh" >/dev/null 2>&1
      prefs="${CAD_PREFS_OVERRIDE:-$OMCTEST_WORK/no-such-registry.plist}"
      stop_orphaned_servers() { :; }
      reap_orphaned_bundle_processes() { :; }
      launch_model_on_port() {
          # $4 is the engine this window is about to stop, which only the cell that launches while
          # its predecessor is still resident has one of, and $5 is the window that can be proven
          # to own it. Recorded because passing them is the whole difference between a server sized
          # for the memory it will have and one sized for the memory it has during the handover.
          printf 'launch\t%s\t%s\t%s\t%s\n' "$1" "$3" "$4" "$5" >> "$SW_LOG"
          LAUNCHED_MODEL_LABEL=$(/usr/bin/basename "$1" .gguf)
          return "${STUB_LAUNCH_RC:-0}"
      }
      stop_window_server() {
          printf 'stop\t%s\t%s\n' "$1" "$(sw_seen_config)" >> "$SW_LOG"
          return 0
      }
      find_free_port_in() { printf '%s\n' "${STUB_PORT:-8199}"; }
      foundation_probe() { printf '%s\t%s\n' "${STUB_FM:-available}" "the on-device model is ready"; }
      # The one failure with a server already running behind it, and the only way to produce it
      # without a machine: a transport builder that comes back empty.
      if [ "${STUB_EMPTY_JSON:-0}" = "1" ]; then
          aichat_acp_transport_json() { :; }
      fi
      "$@" )
}

sw_reset() { # a clean journal, a clean call log, and every stub back to "it works"
    : > "$SW_LOG"
    cad_journal_reset
    alerts_reset
    alert_answers_reset
    # NOT settable as `STUB_x=1 sw ...`: a variable assignment prefixing a FUNCTION call PERSISTS
    # in the shell after it returns (unlike one prefixing a command), so a section that forces a
    # failure would go on forcing it for every section below. Set them after sw_reset, deliberately.
    STUB_LAUNCH_RC=0
    STUB_PORT=8199
    STUB_FM=available
    STUB_EMPTY_JSON=0
}
sw_calls()      { /usr/bin/cut -f1 "$SW_LOG" | /usr/bin/tr '\n' ' ' | /usr/bin/sed 's/ *$//'; }
sw_launch_port() { /usr/bin/awk -F'\t' '$1 == "launch" { print $3 }' "$SW_LOG" | /usr/bin/tail -n 1; }
sw_launch_model() { /usr/bin/awk -F'\t' '$1 == "launch" { print $2 }' "$SW_LOG" | /usr/bin/tail -n 1; }
sw_launch_retiring() { /usr/bin/awk -F'\t' '$1 == "launch" { print $4 }' "$SW_LOG" | /usr/bin/tail -n 1; }
sw_launch_retiring_win() { /usr/bin/awk -F'\t' '$1 == "launch" { print $5 }' "$SW_LOG" | /usr/bin/tail -n 1; }
sw_stop_when()  { /usr/bin/awk -F'\t' '$1 == "stop" { print $3 }' "$SW_LOG" | /usr/bin/tail -n 1; }
# What the element was actually handed, IN THE WINDOW BEING SWITCHED. cad_journal answers for a
# view id across every window in the file, and this file drives a switch aimed at $SWIN from a
# picker running somewhere else - so a bare read could not tell "injected into the chat window"
# from "injected into whatever window happened to write last", which is the one mistake a
# window-scoped handler makes. Field 1 of the journal is the window uuid.
sw_win_journal() { # <view-id>
    /usr/bin/awk -F'\t' -v w="$SWIN" -v t="$1" '$1 == w && $2 == t { sub(/ $/, "", $3); print $3 }' \
        "$OMCTEST_UI/journal.tsv"
}
sw_config()     { sw_win_journal "$CHAT_ID" | /usr/bin/sed -n 's/^omc_set_state config //p' | /usr/bin/tail -n 1; }
sw_configs()    { sw_win_journal "$CHAT_ID" | /usr/bin/grep -c 'omc_set_state config .' | /usr/bin/tr -d ' '; }
sw_bar()        { sw_win_journal "$CE_CHAT_MODEL_BTN_ID" | /usr/bin/sed -n 's/^omc_set_property title //p' | /usr/bin/tail -n 1; }
sw_led()        { sw_win_journal "$CHAT_ID" | /usr/bin/grep 'omc_set_state lead .'; }
sw_appended()   { sw_win_journal "$CHAT_ID" | /usr/bin/grep 'omc_set_state append .'; }
# The MCP config generated for this window's session, which the tools decision creates or removes.
sw_mcp_config() { printf '%s\n' "$HOME/Library/Application Support/Cadabra/Sessions/$SWIN/mcp-config.json"; }

# What the registry says a server was launched FOR. Defined here rather than spelled as a plister
# call at four assertion sites, and read through the same $prefs the library writes.
chat_switch_probe_dialog() { # <server-pid>
    "$plister" get string "$prefs" "/server-info/$1/dialog" 2>/dev/null
}

# A conversation on disk, so a marker has somewhere to be recorded.
cad_hist="$HOME/Library/Application Support/Cadabra/History"
cad_mk_session() { # <sid>
    /bin/mkdir -p "$cad_hist/$1"
    : > "$cad_hist/$1/journal.jsonl"
    printf '{"id": "%s", "created": "2026-08-21", "modelPath": "%s"}\n' "$1" "$MLXREAL" \
        > "$cad_hist/$1/meta.json"
}

# A window running one engine, with nothing held and nothing bound.
# <model> <port-or-empty> [tools-decision]
sw_window() {
    cad_pb_set "aichatv2_modelpath_$SWIN" "$1"
    cad_pb_set "aichatv2_agent_$SWIN" ""
    cad_pb_set "aichatv2_port_$SWIN" "$2"
    cad_pb_set "aichatv2_tools_$SWIN" "${3:-false}"
    cad_pb_set "aichatv2_open_$SWIN" "1"
    cad_pb_set "aichatv2_session_$SWIN" ""
    cad_pb_set "aichatv2_resume_pending_$SWIN" ""
    cad_pb_set "aichatv2_pending_markers_$SWIN" ""
}

# ---------------------------------------------------------------------------
section "MLX to MLX: the conversation is handed to another agent, not another server"
# The case that was refused outright until now, and the one the user hit: two MLX models, no
# server anywhere. The whole switch is the argv, so the ONLY evidence it happened is the injected
# config - and the only evidence it was done right is that nothing was launched or stopped.
sw_reset
sw_window "$MLXREAL" ""
sw chat_engine_switch "$SWIN" "$OTHERMLX" false
check "the switch succeeds"              "0" "$?"
check "the element is given a transport" "1" "$(sw_configs)"
check "  naming the new model directory" "1" "$(cad_has "$(sw_config)" "\"--model\", \"$OTHERMLXREAL\"")"
check "  and not the old one"            "0" "$(cad_has "$(sw_config)" "\"$MLXREAL\"")"
check "nothing is launched or stopped"   ""  "$(sw_calls)"
check "the window is stamped with it"    "$OTHERMLXREAL" "$(cad_pb_get "aichatv2_modelpath_$SWIN")"
check "  and claims no port"             ""  "$(cad_pb_get "aichatv2_port_$SWIN")"
check "the model bar names it"           "Mlx-Other-Model" "$(sw_bar)"
check "and the overlay was raised"       "1" "$(cad_has "$(cad_journal "$BASE_CHAT_OVERLAY_SLOT_ID")" "omc_insert_element")"
check "  then dropped again"             "1" "$(cad_has "$(cad_journal "$BASE_CHAT_OVERLAY_ELEM_ID")" "omc_remove_element")"

# ---------------------------------------------------------------------------
section "GGUF to MLX: the server is stopped, and only after the agent has been replaced"
# ORDER IS THE ASSERTION. The injection is what ends the old agent; until it returns, that agent
# may be mid-request against this server. Stopping the server first fails that request, and the
# failure reaches the transcript as an error item and the journal as an error entry - moments
# before the agent was going to be replaced anyway.
sw_reset
sw_window "$GGUF" "8151"
sw chat_engine_switch "$SWIN" "$MLXDIR" false
check "the switch succeeds"                 "0" "$?"
check "the element is given a transport"    "1" "$(sw_configs)"
check "  naming the model directory"        "1" "$(cad_has "$(sw_config)" "\"--model\", \"$MLXREAL\"")"
check "  and no base URL at all"            "0" "$(cad_has "$(sw_config)" "base-url")"
check "this window's server is stopped"     "stop" "$(sw_calls)"
check "  AFTER the element was reconfigured" "after-inject" "$(sw_stop_when)"
check "and the port claim is released"      ""  "$(cad_pb_get "aichatv2_port_$SWIN")"

section "  and a preparation that fails stops nothing and injects nothing"
# The old engine is still answering: nothing has been stopped yet, so a failure here costs the
# user nothing but an alert.
sw_reset
sw_window "$GGUF" "8151"
STUB_EMPTY_JSON=1
sw chat_engine_switch "$SWIN" "$MLXDIR" false
check "the switch reports failure"       "1" "$?"
check "nothing was injected"             "0" "$(sw_configs)"
check "  and no server was stopped"      ""  "$(sw_calls)"
check "the window keeps its model"       "$GGUF" "$(cad_pb_get "aichatv2_modelpath_$SWIN")"
check "  and its port"                   "8151" "$(cad_pb_get "aichatv2_port_$SWIN")"
check "the user is told"                 "1" "$(alerts_count)"

# ---------------------------------------------------------------------------
section "MLX to GGUF: a server has to exist before the new agent asks for it"
# The agent health-checks llama-server during session/new and gives up in about seven seconds,
# which is far less than a model load - so the launch comes FIRST and the injection second. Which
# means the outgoing MLX agent is still holding its weights while the server is sized, and the
# sizing has to be told so: a server keeps its --fit decision for its whole life, so charging it
# for memory that is freed seconds later is a context it never gets back.
sw_reset
sw_window "$MLXREAL" ""
STUB_PORT=8177
sw chat_engine_switch "$SWIN" "$GGUF" false
check "the switch succeeds"                "0" "$?"
check "a server is launched, none stopped" "launch" "$(sw_calls)"
check "  for the chosen model"             "$GGUF" "$(sw_launch_model)"
check "  on the port this window claimed"  "8177"  "$(sw_launch_port)"
check "  told which engine is retiring"    "$MLXREAL" "$(sw_launch_retiring)"
# Tools were OFF for this window, so its agent carries no --mcp-config and cannot be picked out of
# the process table. Claiming otherwise would let the sizing discount another window's engine.
check "  but not claimed to be identifiable" "" "$(sw_launch_retiring_win)"
check "the port is stamped for the window" "8177"  "$(cad_pb_get "aichatv2_port_$SWIN")"
check "the element is given a transport"   "1" "$(sw_configs)"
check "  pointed at that port"             "1" "$(cad_has "$(sw_config)" '"--base-url", "http://127.0.0.1:8177/v1"')"
check "  and carrying no --model"          "0" "$(cad_has "$(sw_config)" '"--model"')"
check "the model bar names the new model"  "Tiny-Q4_K_M" "$(sw_bar)"

section "  and a window running tools can prove which agent is its own"
# With tools on the outgoing agent carries --mcp-config .../Sessions/<win>/, which no other
# window's argv can contain. Passing the window is what lets the scan read "not found" as "my agent
# is already gone" rather than falling back to whichever engine happens to run the same model.
sw_reset
sw_window "$MLXREAL" "" true
STUB_PORT=8178
sw chat_engine_switch "$SWIN" "$GGUF" true
check "the switch succeeds"                "0" "$?"
check "the retiring engine is named"       "$MLXREAL" "$(sw_launch_retiring)"
check "  and so is the window that owns it" "$SWIN" "$(sw_launch_retiring_win)"

section "  a launch that never comes up leaves the window on the model it had"
sw_reset
sw_window "$MLXREAL" ""
STUB_LAUNCH_RC=11
STUB_PORT=8177
sw chat_engine_switch "$SWIN" "$GGUF" false
check "the switch reports failure"    "1" "$?"
check "nothing was injected"          "0" "$(sw_configs)"
check "the model stamp is put back"   "$MLXREAL" "$(cad_pb_get "aichatv2_modelpath_$SWIN")"
check "  and the port is unclaimed"   ""  "$(cad_pb_get "aichatv2_port_$SWIN")"

section "  and a launch that DID come up is stopped when the transport is refused"
# THE LEAK THIS EXISTS TO CLOSE. The server is up and registered to this window; nothing will ever
# talk to it. The close handler stops one server per window, so a later gguf-to-gguf switch on a
# fresh port would strand this one until the app quits.
sw_reset
sw_window "$MLXREAL" ""
STUB_EMPTY_JSON=1
STUB_PORT=8177
sw chat_engine_switch "$SWIN" "$GGUF" false
check "the switch reports failure"        "1" "$?"
check "the server it started is stopped"  "launch stop" "$(sw_calls)"
check "  with nothing having been injected" "before-inject" "$(sw_stop_when)"
check "and the port is unclaimed"         ""  "$(cad_pb_get "aichatv2_port_$SWIN")"
check "the window keeps its model"        "$MLXREAL" "$(cad_pb_get "aichatv2_modelpath_$SWIN")"

# ---------------------------------------------------------------------------
section "GGUF to GGUF: the one cell with nothing to re-inject"
# The agent's argv names the PORT, not the model, and its conversation array survives a server
# restart underneath it - which is the semantics this cell wants. Re-injecting here would throw
# that away and re-prime a fresh agent for no reason.
sw_reset
sw_window "$GGUF" "8151"
sw chat_engine_switch "$SWIN" "$OTHER" false
check "the switch succeeds"              "0" "$?"
check "the server restarts, nothing else" "launch" "$(sw_calls)"
check "  on the window's own port"       "8151" "$(sw_launch_port)"
# Nothing of this window's is retiring here: the outgoing server on this port was TERMed and
# waited out by the launch itself, and the agent that survives holds no weights of its own. Naming
# a retiring engine here would discount a model that is genuinely gone and over-commit the GPU.
check "  and nothing is retiring under it" "" "$(sw_launch_retiring)"
check "NOTHING is injected"              "0" "$(sw_configs)"
check "the window keeps that port"       "8151" "$(cad_pb_get "aichatv2_port_$SWIN")"
check "and is stamped with the new model" "$OTHER" "$(cad_pb_get "aichatv2_modelpath_$SWIN")"
check "the model bar names it"           "Other-Q5_K_S" "$(sw_bar)"

# ---------------------------------------------------------------------------
