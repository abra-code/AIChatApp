check "  and it is in the journal"           "1" \
    "$(cad_has "$(/bin/cat "$cad_hist/20260821T000000Z-switch/journal.jsonl")" '"kind": "modelChanged"')"
check "  while the title stays the conversation's" "0" "$(ui_calls omc_window)"

section "  a switch before the first message queues behind the line that opens it"
# Nothing has been said into this window yet, so the opening marker is still held for the first
# message. The switch joins it there instead of being recorded on its own - a brand-new window has
# no session directory to record into, and both lines belong in front of that first message.
sw_reset
sw_window "$MLXREAL" ""
cad_mk_session "20260821T000002Z-held"
cad_pb_set "aichatv2_session_$SWIN" "20260821T000002Z-held"
cad_call_lib aichat.history.library.sh history_marker_lead "$SWIN" "$CHAT_ID" started "Mlx-Test-Model"
cad_journal_reset
sw chat_engine_switch "$SWIN" "$OTHERMLX" false
held=$(cad_pb_get "aichatv2_pending_markers_$SWIN")
check "the window now holds two lines"   "2" "$(printf '%s\n' "$held" | /usr/bin/grep -c '"type": "sessionEvent"')"
check "  the second being the handover"  "1" "$(cad_has "$held" '"kind": "modelChanged"')"
check "  published to the element"       "1" "$(cad_has "$(sw_led)" '"kind": "modelChanged"')"
# Held, not shown - and this window HAS a session to record into, so the queue is genuinely what
# refused to record rather than the armed-resume floor underneath it.
check "and nothing is put on screen"     ""  "$(sw_appended)"
check "  nor recorded yet"               "0" \
    "$(cad_has "$(/bin/cat "$cad_hist/20260821T000002Z-held/journal.jsonl" 2>/dev/null)" 'modelChanged')"

section "  and a conversation only opened for reading records nothing yet"
# The armed resume is the floor under the queue: a window handed a conversation it has not been
# spoken to shows no marker and queues none, and a switch must not write into a transcript
# nothing has happened in.
sw_reset
sw_window "$MLXREAL" ""
cad_mk_session "20260821T000001Z-read"
